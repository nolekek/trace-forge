//! # Storage Models & Domain Types
//!
//! Error classifications, summary metrics, and configuration options
//! for the TraceForge storage layer.

use std::time::Duration;
use serde::{Deserialize, Serialize};
use thiserror::Error;
use traceforge_core::events::{EventKind, TraceEvent};

/// Storage domain errors.
#[derive(Debug, Error)]
pub enum StorageError {
    #[error("Database error: {0}")]
    Database(#[from] rusqlite::Error),

    #[error("Serialization / deserialization error: {0}")]
    Serialization(#[from] serde_json::Error),

    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),

    #[error("Async flusher channel closed or worker terminated")]
    ChannelClosed,

    #[error("Flusher queue buffer is full (backpressure threshold reached)")]
    QueueFull,

    #[error("Storage initialization error: {0}")]
    Initialization(String),

    #[error("Worker task error: {0}")]
    TaskError(String),
}

/// Aggregated telemetry summary for an agent execution session.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct SessionSummary {
    /// Total recorded trace events in this session.
    pub total_events: u64,
    /// Cumulative input/prompt tokens consumed by LLM calls.
    pub total_prompt_tokens: u64,
    /// Cumulative output/completion tokens generated by LLMs.
    pub total_completion_tokens: u64,
    /// Total financial expenditure in USD across model calls.
    pub total_cost_usd: f64,
    /// Mean execution latency across all events in microseconds.
    pub avg_latency_us: f64,
    /// Number of loop detection anomalies detected.
    pub loop_detections_count: u64,
    /// Number of policy invariant violations flagged.
    pub policy_violations_count: u64,
}

impl SessionSummary {
    /// Computes summary statistics in-memory from a sequence of trace events.
    pub fn from_events<'a>(events: impl IntoIterator<Item = &'a TraceEvent>) -> Self {
        let mut total_events = 0u64;
        let mut total_prompt_tokens = 0u64;
        let mut total_completion_tokens = 0u64;
        let mut total_cost_usd = 0.0;
        let mut total_latency_us = 0u64;
        let mut loop_detections_count = 0u64;
        let mut policy_violations_count = 0u64;

        for evt in events {
            total_events += 1;
            if let Some(usage) = &evt.token_usage {
                total_prompt_tokens += usage.prompt_tokens as u64;
                total_completion_tokens += usage.completion_tokens as u64;
            }
            total_cost_usd += evt.cost_usd;
            total_latency_us += evt.latency_us as u64;

            if evt.kind == EventKind::LoopDetected {
                loop_detections_count += 1;
            }

            if let Some(policy) = &evt.policy_result {
                if !policy.allow {
                    policy_violations_count += (policy.violations.len() as u64).max(1);
                } else {
                    policy_violations_count += policy.violations.len() as u64;
                }
            }
        }

        let avg_latency_us = if total_events > 0 {
            total_latency_us as f64 / total_events as f64
        } else {
            0.0
        };

        Self {
            total_events,
            total_prompt_tokens,
            total_completion_tokens,
            total_cost_usd,
            avg_latency_us,
            loop_detections_count,
            policy_violations_count,
        }
    }
}

/// Configuration settings for the asynchronous batch telemetry flusher.
#[derive(Debug, Clone)]
pub struct BatchFlusherConfig {
    /// Maximum capacity of the bounded in-memory channel (default 10,000).
    pub channel_capacity: usize,
    /// Number of accumulated events before triggering an immediate batch flush (default 100).
    pub batch_size: usize,
    /// Periodic duration after which buffered events are flushed regardless of batch size (default 250ms).
    pub flush_interval: Duration,
}

impl Default for BatchFlusherConfig {
    fn default() -> Self {
        Self {
            channel_capacity: 10_000,
            batch_size: 100,
            flush_interval: Duration::from_millis(250),
        }
    }
}
